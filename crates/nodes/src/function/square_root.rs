pub(crate) fn evaluate(value: f32) -> f32 {
    if value < f32::MIN_POSITIVE || value.is_nan() {
        return 0.0;
    }
    if value.is_infinite() {
        return value;
    }
    let bits = value.to_bits();
    let exponent = (bits >> 23) as i32 - 127;
    let parity = (exponent & 1) as usize;
    let interval = ((bits >> 17) & 63) as usize;
    let [constant, slope, curvature] = INTERVALS[parity][interval].map(i64::from);
    let fraction = bits & 0x1_ffff;
    let square = i64::from(square_fraction(fraction >> 1));
    let fixed = (constant << 15) + ((slope * i64::from(fraction)) << parity) + 2 * curvature * square;
    // Round to the nearest significand, with exact halfway cases rounded down.
    let significand = ((fixed + 65_535) >> 17) as u32;
    let scale = (exponent.div_euclid(2) + 126) as u32;
    f32::from_bits((scale << 23) + significand)
}
